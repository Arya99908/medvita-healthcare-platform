-- Verified clinicians may append a review only with the patient's separate
-- clinical-notes consent. The AI report and its source links remain unchanged.
create unique index if not exists ai_reports_patient_id_id_unique on public.ai_reports(patient_id,id);
create table public.ai_report_reviews (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.patient_profiles(id) on delete cascade,
  report_id uuid not null references public.ai_reports(id) on delete cascade,
  doctor_user_id uuid not null references auth.users(id) on delete restrict,
  review_outcome text not null check (review_outcome in ('reviewed','needs_correction','rejected')),
  review_note text not null check (length(trim(review_note)) between 1 and 4000),
  created_at timestamptz not null default now(),
  constraint ai_report_reviews_patient_report_fk foreign key (patient_id, report_id)
    references public.ai_reports(patient_id, id) on delete cascade
);

create index ai_report_reviews_patient_created_idx on public.ai_report_reviews(patient_id,created_at desc);
create index ai_report_reviews_report_created_idx on public.ai_report_reviews(report_id,created_at desc);
alter table public.ai_report_reviews enable row level security;
revoke all on public.ai_report_reviews from anon, authenticated;
grant select, insert on public.ai_report_reviews to authenticated;

create policy "linked readers can read AI report reviews" on public.ai_report_reviews
  for select to authenticated using (medvita_private.has_patient_access(patient_id,'read'));
create policy "consented verified doctor can append AI report review" on public.ai_report_reviews
  for insert to authenticated with check (
    doctor_user_id=auth.uid()
    and medvita_private.has_patient_access(patient_id,'clinical_notes')
    and exists(select 1 from public.doctors d where d.user_id=auth.uid() and d.verification_status='verified')
    and exists(select 1 from public.ai_reports r where r.id=report_id and r.patient_id=ai_report_reviews.patient_id
      and r.report_type='patient_history_summary' and r.visibility='general')
  );

create trigger record_ai_report_review_activity after insert on public.ai_report_reviews
  for each row execute function medvita_private.record_patient_activity();

comment on table public.ai_report_reviews is
  'Append-only verified-clinician review history for general patient history summaries; requires active patient clinical_notes consent.';

